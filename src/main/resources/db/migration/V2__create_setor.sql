CREATE TABLE setor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    codigo VARCHAR(30) NOT NULL,
    nome VARCHAR(200) NOT NULL,
    nome_normalizado VARCHAR(200) NOT NULL,
    descricao VARCHAR(1000),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_setor_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT uk_setor_empresa_codigo UNIQUE (empresa_id, codigo),
    CONSTRAINT uk_setor_empresa_nome UNIQUE (empresa_id, nome_normalizado)
);
