CREATE TABLE motivo_parada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    codigo VARCHAR(50) NOT NULL,
    nome VARCHAR(200) NOT NULL,
    descricao VARCHAR(1000),
    categoria VARCHAR(50),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_motivo_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT uk_motivo_empresa_codigo UNIQUE (empresa_id, codigo)
);
CREATE INDEX idx_motivo_empresa_ativo ON motivo_parada (empresa_id, ativo);
CREATE INDEX idx_motivo_empresa_nome ON motivo_parada (empresa_id, nome);
