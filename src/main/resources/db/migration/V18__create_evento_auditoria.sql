CREATE TABLE evento_auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT,
    usuario_id BIGINT,
    usuario_nome_snapshot VARCHAR(200),
    tipo_recurso VARCHAR(40) NOT NULL,
    recurso_id BIGINT,
    acao VARCHAR(40) NOT NULL,
    origem VARCHAR(30) NOT NULL,
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL,
    dados_anteriores TEXT,
    dados_novos TEXT,
    metadados TEXT,
    correlation_id VARCHAR(100)
);

CREATE INDEX idx_evento_auditoria_empresa_data ON evento_auditoria (empresa_id, data_hora);
CREATE INDEX idx_evento_auditoria_empresa_recurso ON evento_auditoria (empresa_id, tipo_recurso, recurso_id);
CREATE INDEX idx_evento_auditoria_empresa_usuario_data ON evento_auditoria (empresa_id, usuario_id, data_hora);
CREATE INDEX idx_evento_auditoria_empresa_acao_data ON evento_auditoria (empresa_id, acao, data_hora);
CREATE INDEX idx_evento_auditoria_correlation ON evento_auditoria (correlation_id);
