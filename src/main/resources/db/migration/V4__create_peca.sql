CREATE TABLE peca (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    codigo VARCHAR(80) NOT NULL,
    descricao VARCHAR(300) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_peca_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT uk_peca_empresa_codigo UNIQUE (empresa_id, codigo)
);
CREATE INDEX idx_peca_empresa_descricao ON peca (empresa_id, descricao);
CREATE INDEX idx_peca_empresa_ativo ON peca (empresa_id, ativo);
