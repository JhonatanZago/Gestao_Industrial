CREATE TABLE tempo_padrao_producao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    peca_id BIGINT NOT NULL,
    setor_id BIGINT NOT NULL,
    maquina_id BIGINT,
    segundos DECIMAL(19,3) NOT NULL,
    base_tempo VARCHAR(20) NOT NULL,
    quantidade_referencia DECIMAL(19,3),
    vigencia_inicio DATE NOT NULL,
    vigencia_fim DATE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_tempo_padrao_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_tempo_padrao_peca FOREIGN KEY (peca_id) REFERENCES peca(id),
    CONSTRAINT fk_tempo_padrao_setor FOREIGN KEY (setor_id) REFERENCES setor(id),
    CONSTRAINT fk_tempo_padrao_maquina FOREIGN KEY (maquina_id) REFERENCES maquina(id),
    CONSTRAINT ck_tempo_padrao_segundos_positivo CHECK (segundos > 0),
    CONSTRAINT ck_tempo_padrao_vigencia_valida CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
    CONSTRAINT ck_tempo_padrao_base_valida CHECK (base_tempo IN ('POR_UNIDADE', 'POR_LOTE')),
    CONSTRAINT ck_tempo_padrao_referencia_valida CHECK (
        (base_tempo = 'POR_UNIDADE' AND quantidade_referencia IS NULL)
        OR (base_tempo = 'POR_LOTE' AND quantidade_referencia > 0)
    )
);
CREATE INDEX idx_tempo_padrao_empresa_contexto ON tempo_padrao_producao(empresa_id, peca_id, setor_id, maquina_id);
CREATE INDEX idx_tempo_padrao_vigencia ON tempo_padrao_producao(empresa_id, vigencia_inicio, vigencia_fim, ativo);
