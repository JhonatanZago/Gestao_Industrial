create table maquina (
    id bigint generated by default as identity primary key,
    empresa_id bigint not null,
    setor_id bigint not null,
    codigo varchar(50) not null,
    nome varchar(200) not null,
    descricao varchar(1000),
    tipo varchar(50),
    ativo boolean not null default true,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint uk_maquina_empresa_codigo unique (empresa_id, codigo),
    constraint fk_maquina_empresa foreign key (empresa_id) references empresa(id),
    constraint fk_maquina_setor foreign key (setor_id) references setor(id)
);
create index idx_maquina_empresa_setor on maquina(empresa_id, setor_id);
create index idx_maquina_empresa_ativo on maquina(empresa_id, ativo);

create table turno (
    id bigint generated by default as identity primary key,
    empresa_id bigint not null,
    codigo varchar(50) not null,
    nome varchar(200) not null,
    hora_inicio time not null,
    hora_fim time not null,
    ativo boolean not null default true,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint uk_turno_empresa_codigo unique (empresa_id, codigo),
    constraint ck_turno_horarios_diferentes check (hora_inicio <> hora_fim),
    constraint fk_turno_empresa foreign key (empresa_id) references empresa(id)
);
create index idx_turno_empresa_ativo on turno(empresa_id, ativo);
