CREATE TABLE parada_producao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    registro_producao_id BIGINT NOT NULL,
    motivo_parada_id BIGINT NOT NULL,
    inicio TIMESTAMP NOT NULL,
    fim TIMESTAMP NOT NULL,
    observacao VARCHAR(1000),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_parada_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_parada_producao FOREIGN KEY (registro_producao_id) REFERENCES registro_producao(id),
    CONSTRAINT fk_parada_motivo FOREIGN KEY (motivo_parada_id) REFERENCES motivo_parada(id),
    CONSTRAINT ck_parada_intervalo_valido CHECK (fim > inicio)
);
CREATE INDEX idx_parada_producao_periodo ON parada_producao (registro_producao_id, inicio, fim);
CREATE INDEX idx_parada_empresa_inicio ON parada_producao (empresa_id, inicio);
CREATE INDEX idx_parada_motivo ON parada_producao (motivo_parada_id);
