CREATE TABLE valor_producao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    peca_id BIGINT NOT NULL,
    setor_id BIGINT NOT NULL,
    maquina_id BIGINT,
    tipo_valor VARCHAR(24) NOT NULL,
    valor_unitario DECIMAL(19,6) NOT NULL,
    moeda VARCHAR(3) NOT NULL,
    vigencia_inicio DATE NOT NULL,
    vigencia_fim DATE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_valor_producao_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_valor_producao_peca FOREIGN KEY (peca_id) REFERENCES peca(id),
    CONSTRAINT fk_valor_producao_setor FOREIGN KEY (setor_id) REFERENCES setor(id),
    CONSTRAINT fk_valor_producao_maquina FOREIGN KEY (maquina_id) REFERENCES maquina(id),
    CONSTRAINT ck_valor_producao_positivo CHECK (valor_unitario > 0),
    CONSTRAINT ck_valor_producao_moeda CHECK (moeda = UPPER(moeda) AND CHAR_LENGTH(moeda) = 3),
    CONSTRAINT ck_valor_producao_tipo CHECK (tipo_valor IN ('VALOR_PROCESSAMENTO', 'VALOR_PRODUCAO', 'RECEITA_ESTIMADA')),
    CONSTRAINT ck_valor_producao_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio)
);
CREATE INDEX idx_valor_producao_empresa_contexto ON valor_producao(empresa_id, peca_id, setor_id, maquina_id);
CREATE INDEX idx_valor_producao_vigencia ON valor_producao(empresa_id, tipo_valor, moeda, vigencia_inicio, vigencia_fim, ativo);
