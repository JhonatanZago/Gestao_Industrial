CREATE TABLE registro_producao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    setor_id BIGINT NOT NULL,
    funcionario_id BIGINT NOT NULL,
    peca_id BIGINT NOT NULL,
    quantidade DECIMAL(19,3) NOT NULL,
    inicio TIMESTAMP NOT NULL,
    fim TIMESTAMP NOT NULL,
    observacao VARCHAR(1000),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_producao_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_producao_setor FOREIGN KEY (setor_id) REFERENCES setor(id),
    CONSTRAINT fk_producao_funcionario FOREIGN KEY (funcionario_id) REFERENCES funcionario(id),
    CONSTRAINT fk_producao_peca FOREIGN KEY (peca_id) REFERENCES peca(id),
    CONSTRAINT ck_producao_quantidade_positiva CHECK (quantidade > 0),
    CONSTRAINT ck_producao_intervalo_valido CHECK (fim > inicio)
);
CREATE INDEX idx_producao_empresa_inicio ON registro_producao (empresa_id, inicio);
CREATE INDEX idx_producao_funcionario_periodo ON registro_producao (funcionario_id, inicio, fim);
CREATE INDEX idx_producao_setor_inicio ON registro_producao (setor_id, inicio);
CREATE INDEX idx_producao_peca_inicio ON registro_producao (peca_id, inicio);
