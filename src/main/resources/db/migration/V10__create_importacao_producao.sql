create table importacao_producao (
 id bigint generated by default as identity primary key,
 empresa_id bigint not null, setor_id bigint not null, nome_arquivo varchar(255) not null,
 hash_arquivo varchar(64) not null, status varchar(20) not null, total_linhas integer not null default 0,
 linhas_validas integer not null default 0, linhas_invalidas integer not null default 0, linhas_importadas integer not null default 0,
 iniciado_em timestamp with time zone not null, finalizado_em timestamp with time zone, created_at timestamp with time zone not null,
 constraint fk_import_empresa foreign key (empresa_id) references empresa(id), constraint fk_import_setor foreign key (setor_id) references setor(id)
);
create index idx_import_empresa_created on importacao_producao(empresa_id, created_at);
create index idx_import_empresa_hash on importacao_producao(empresa_id, setor_id, hash_arquivo);
create index idx_import_status on importacao_producao(empresa_id, status);
create table resultado_linha_importacao (
 id bigint generated by default as identity primary key, importacao_id bigint not null, numero_linha integer not null,
 status varchar(20) not null, codigo_funcionario varchar(100), codigo_peca varchar(100), codigo_erro varchar(80), mensagem varchar(1000),
 constraint fk_resultado_import foreign key (importacao_id) references importacao_producao(id)
);
create index idx_resultado_import_linha on resultado_linha_importacao(importacao_id, numero_linha);
