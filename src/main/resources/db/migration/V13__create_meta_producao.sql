CREATE TABLE meta_producao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    descricao VARCHAR(1000),
    tipo_meta VARCHAR(20) NOT NULL,
    setor_id BIGINT,
    funcionario_id BIGINT,
    peca_id BIGINT,
    maquina_id BIGINT,
    turno_id BIGINT,
    quantidade_meta DECIMAL(19,3) NOT NULL,
    periodicidade VARCHAR(20) NOT NULL,
    vigencia_inicio DATE NOT NULL,
    vigencia_fim DATE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_meta_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_meta_setor FOREIGN KEY (setor_id) REFERENCES setor(id),
    CONSTRAINT fk_meta_funcionario FOREIGN KEY (funcionario_id) REFERENCES funcionario(id),
    CONSTRAINT fk_meta_peca FOREIGN KEY (peca_id) REFERENCES peca(id),
    CONSTRAINT fk_meta_maquina FOREIGN KEY (maquina_id) REFERENCES maquina(id),
    CONSTRAINT fk_meta_turno FOREIGN KEY (turno_id) REFERENCES turno(id),
    CONSTRAINT ck_meta_quantidade_positiva CHECK (quantidade_meta > 0),
    CONSTRAINT ck_meta_vigencia_valida CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
    CONSTRAINT ck_meta_tipo_valido CHECK (tipo_meta IN ('EMPRESA', 'SETOR', 'FUNCIONARIO', 'PECA', 'MAQUINA', 'TURNO', 'COMPOSTA')),
    CONSTRAINT ck_meta_periodicidade_valida CHECK (periodicidade IN ('TURNO', 'DIA', 'SEMANA', 'MES'))
);
CREATE INDEX idx_meta_empresa_contexto ON meta_producao(empresa_id, tipo_meta, setor_id, funcionario_id, peca_id, maquina_id, turno_id);
CREATE INDEX idx_meta_vigencia ON meta_producao(empresa_id, periodicidade, vigencia_inicio, vigencia_fim, ativo);
