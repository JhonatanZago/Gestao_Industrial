create table importacao_baseline (
    id bigint generated by default as identity primary key,
    empresa_id bigint not null,
    setor_id bigint not null,
    source_key varchar(64) not null,
    nome_arquivo varchar(255) not null,
    hash_arquivo varchar(64) not null,
    observado_em timestamp with time zone not null,
    constraint uk_import_baseline_source unique (empresa_id, setor_id, source_key, nome_arquivo)
);
create index idx_import_baseline_scope on importacao_baseline (empresa_id, setor_id);
