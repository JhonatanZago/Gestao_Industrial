CREATE TABLE ai_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    sector_id BIGINT,
    file_name VARCHAR(255) NOT NULL,
    title VARCHAR(200) NOT NULL,
    content_type VARCHAR(20) NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    version VARCHAR(80) NOT NULL,
    status VARCHAR(20) NOT NULL,
    required_permission VARCHAR(80) NOT NULL,
    normalized_content TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_ai_document_empresa_status ON ai_document (empresa_id, status);
CREATE INDEX idx_ai_document_empresa_hash ON ai_document (empresa_id, content_hash);

CREATE TABLE ai_document_chunk (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    empresa_id BIGINT NOT NULL,
    sector_id BIGINT,
    chunk_index INTEGER NOT NULL,
    content TEXT NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    version VARCHAR(80) NOT NULL,
    required_permission VARCHAR(80) NOT NULL,
    active BOOLEAN NOT NULL
);

CREATE INDEX idx_ai_chunk_document_version ON ai_document_chunk (document_id, version, active);
CREATE INDEX idx_ai_chunk_empresa_sector ON ai_document_chunk (empresa_id, sector_id, active);

INSERT INTO permissao (codigo, nome)
SELECT 'AI_DOCUMENTO_GERENCIAR', 'Gerenciar documentos do assistente'
WHERE NOT EXISTS (SELECT 1 FROM permissao WHERE codigo = 'AI_DOCUMENTO_GERENCIAR');

INSERT INTO perfil_permissao (perfil_id, permissao_id)
SELECT p.id, x.id FROM perfil p CROSS JOIN permissao x
WHERE p.codigo = 'ADMINISTRADOR'
  AND x.codigo = 'AI_DOCUMENTO_GERENCIAR'
  AND NOT EXISTS (SELECT 1 FROM perfil_permissao pp WHERE pp.perfil_id = p.id AND pp.permissao_id = x.id);
